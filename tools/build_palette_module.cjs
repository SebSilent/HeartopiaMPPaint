// Regenerates assets/js/data/heartopia-palette.js from the two JSON tables in
// assets/data, so the site ships the palette as a plain ES module (no fetch,
// works offline/file://).
const fs = require('fs');
const src = JSON.parse(fs.readFileSync('assets/data/heartopia-palette.json', 'utf8'));

// Heartopia's own palette table: 16 base colours, 13 of them with a detail row.
// Vendored into the repo so a fresh clone can rebuild without the scrape.
const game = JSON.parse(fs.readFileSync('assets/data/heartopia-game-palette.json', 'utf8'));
const base = game.base.map((b) => ({ code: b.code, hex: b.hex.toUpperCase() }));

const body = JSON.stringify(src.groups.map((g) => ({
  group: g.group,
  main: g.mainColor,
  colors: g.colors,
})));

// The 13 detail rows are exactly our 13 groups, in this order, with the same
// shade counts (5, then 10 x 12). Codes are what you dial in the game, so the
// picker and the blueprint can print them.
const DETAIL_KEYS = game.detailKeys;
const EXPECTED_COUNTS = DETAIL_KEYS.map((k) => game.detail[k].length);
const counts = src.groups.map((g) => g.colors.length);
if (counts.join(',') !== EXPECTED_COUNTS.join(',')) {
  throw new Error('group shade counts ' + counts.join(',') + ' no longer match the game detail rows ' + EXPECTED_COUNTS.join(','));
}

const out = `/* GENERATED by tools/build_palette_module.cjs - do not edit by hand.
 * Heartopia painting palette, ${src.groups.length} colour groups / ${src.totalColors} selectable shades.
 * Shades extracted from ${src.source}
 * Colour codes from the game's own table, see assets/data/heartopia-game-palette.json
 */

// The game's detail rows, in group order. Group g, shade s is code KEY-S.
const DETAIL_KEYS = ${JSON.stringify(DETAIL_KEYS)};

export const HEARTOPIA_GROUPS = ${body};

// Flat paint index: 0 = empty (paper), 1..N = palette shades in group order.
export const FLAT_COLORS = [null, ...HEARTOPIA_GROUPS.flatMap((g) => g.colors)];

// Index of each group's first shade, so the UI can jump between groups.
export const GROUP_START = HEARTOPIA_GROUPS.map((g) => {
  let i = 1;
  for (const other of HEARTOPIA_GROUPS) {
    if (other === g) break;
    i += other.colors.length;
  }
  return i;
});

// Heartopia's own colour numbers, parallel to FLAT_COLORS. Paint index i is
// code COLOR_CODES[i] in the game's picker, e.g. 05-8.
export const COLOR_CODES = [null, ...HEARTOPIA_GROUPS.flatMap((g, gi) => g.colors.map((_, si) => DETAIL_KEYS[gi] + '-' + (si + 1)))];

// The game's 16 base colours. 02, 03 and 04 have no detail row of their own.
export const GAME_BASE = ${JSON.stringify(base)};

export function codeFor(index) {
  return COLOR_CODES[index] || null;
}
`;

fs.writeFileSync('assets/js/data/heartopia-palette.js', out);
console.log('wrote assets/js/data/heartopia-palette.js:', src.totalColors, 'shades,', src.groups.length, 'groups, codes', DETAIL_KEYS[0] + '-1..' + DETAIL_KEYS[12] + '-10');
