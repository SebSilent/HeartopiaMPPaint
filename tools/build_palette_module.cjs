// Regenerates assets/data/heartopia-palette.js from assets/data/heartopia-palette.json
// so the site can ship the palette as a plain ES module (no fetch, works offline/file://).
const fs = require('fs');
const src = JSON.parse(fs.readFileSync('assets/data/heartopia-palette.json', 'utf8'));

const body = JSON.stringify(src.groups.map((g) => ({
  group: g.group,
  main: g.mainColor,
  colors: g.colors,
})));

const out = `/* GENERATED by tools/build_palette_module.js - do not edit by hand.
 * Heartopia painting palette, 13 colour groups / ${src.totalColors} selectable shades.
 * Extracted from ${src.source}
 */
export const HEARTOPIA_GROUPS = ${body};

// Flat paint index: 0 = empty (paper), 1..N = palette shades in group order.
export const FLAT_COLORS = [null, ...HEARTOPIA_GROUPS.flatMap((g) => g.colors)];

// Index of each group's first shade, so the UI can jump between groups.
export const GROUP_START = HEARTOPIA_GROUPS.map((g) => {
  let i = 1;
  for (const other of HEARTOPIA_GROUPS) {
    if (other === g) break;
    i += other.colors.length;
  }
  return i;
});
`;

fs.writeFileSync('assets/js/data/heartopia-palette.js', out);
console.log('wrote assets/js/data/heartopia-palette.js:', src.totalColors, 'shades,', src.groups.length, 'groups');
