const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const src = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets/data/heartopia-outlines.json'), 'utf8'));

const body = JSON.stringify(src.items);
const out = `/* GENERATED by tools/build_outline_module.cjs from assets/data/heartopia-outlines.json.
 * Garment silhouettes in cell coordinates, one ring per face, from the game's
 * own pattern data. Fractional coordinates are real: the outline is not grid
 * aligned, so a cell is decided by whether its centre falls inside.
 */
export const OUTLINE_DATA = ${body};

export const OUTLINE_SOURCE = ${JSON.stringify(src.source)};
`;

fs.writeFileSync(path.join(ROOT, 'assets/js/data/heartopia-outlines.js'), out);
const faces = Object.values(src.items).reduce((n, g) => n + Object.keys(g).length, 0);
console.log('wrote assets/js/data/heartopia-outlines.js:', Object.keys(src.items).length, 'items,', faces, 'faces');
